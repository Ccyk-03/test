def seed_all(db: Session) -> None:
    """幂等写入种子数据：默认管理员、默认普通用户、6 单元配置、三份调用指令 s1/s2/s3。"""
    # 1. 默认管理员账号 admin / admin123（系统仅保留一个管理员）
    if db.query(User).filter(User.username == "admin").first() is None:
        db.add(User(
            username="admin",
            password_hash=hash_password("admin123"),
            role="admin",
            is_active=True,
        ))

    # 1.1 默认普通用户账号 test / 123456
    if db.query(User).filter(User.username == "test").first() is None:
        db.add(User(
            username="test",
            password_hash=hash_password("123456"),
            role="user",
            is_active=True,
        ))

    # 2. 6 个优化单元默认配置
    for unit_no, name, template, instruction in DEFAULT_UNITS:
        if db.query(UnitConfig).filter(UnitConfig.unit_no == unit_no).first() is None:
            db.add(UnitConfig(
                unit_no=unit_no,
                name=name,
                default_template=template,
                unit_instruction=instruction,
                updated_at=datetime.now(),
            ))

    # 3. 三份调用指令 s1/s2/s3（按 key 幂等）
    for key, text in GLOBAL_INSTRUCTIONS.items():
        if db.query(GlobalConfig).filter(GlobalConfig.key == key).first() is None:
            db.add(GlobalConfig(
                key=key,
                value=text,
                updated_at=datetime.now(),
            ))

    db.commit()
